def reviewer_system_prompt(role: str) -> str:
    """Собирает системный промпт ролевого ревьюера: общие правила + зона ответственности."""
    try:
        brief = ROLE_BRIEFS[role]
    except KeyError as exc:
        raise KeyError(f"Неизвестная роль ревьюера: {role}") from exc
    return f"{SHARED_REVIEWER_RULES}\n\n{brief}"
